/// Writes a small image to a file of this test's own.
fn image_file(name: &str) -> PathBuf {
    use image::{ImageFormat, Rgba, RgbaImage};
    let path =
        std::env::temp_dir().join(format!("unkludge-cli-it-{}-{name}.png", std::process::id()));
    RgbaImage::from_pixel(32, 32, Rgba([255, 0, 0, 255]))
        .save_with_format(&path, ImageFormat::Png)
        .unwrap();
    path
}

#[test]
fn screen_prints_a_summary_not_every_chunk() {
    let path = image_file("summary");
    let output = unkludge(&[
        "--dry-run",
        "--pid",
        "0265",
        "--timing",
        "screen",
        path.to_str().unwrap(),
    ]);
    std::fs::remove_file(&path).unwrap();
    assert_eq!(output.status.code(), Some(0), "{}", stderr(&output));
    let text = stdout(&output);
    assert!(text.lines().count() < 17, "{text}");
    assert!(
        text.contains("... 213 more chunks of frame 0 ..."),
        "{text}"
    );
    assert!(
        text.contains("Reports: 1 x 0x84, 2 x 0x0D, 215 x 0x0C"),
        "{text}"
    );
    assert!(text.contains("Total: "), "{text}");
    assert!(
        text.contains("Chunks: 215 sent, 215 acknowledged"),
        "{text}"
    );
    assert!(text.contains("Ack wait: min "), "{text}");
    assert!(text.contains("Send: min "), "{text}");
    assert!(text.ends_with("ms\n"), "{text}");
    assert!(stderr(&output).contains("makes up its acks"));
}

#[test]
fn verbose_prints_every_chunk_in_full() {
    let path = image_file("verbose");
    let output = unkludge(&[
        "--dry-run",
        "--pid",
        "0265",
        "--verbose",
        "screen",
        path.to_str().unwrap(),
    ]);
    std::fs::remove_file(&path).unwrap();
    assert_eq!(output.status.code(), Some(0));
    let text = stdout(&output);
    assert_eq!(text.matches("09 0C 00 ").count(), 215, "chunks");
}

#[test]
fn verbose_timing_prints_every_ack() {
    let path = image_file("ack-lines");
    let output = unkludge(&[
        "--dry-run",
        "--pid",
        "0265",
        "--timing",
        "--verbose",
        "screen",
        path.to_str().unwrap(),
    ]);
    std::fs::remove_file(&path).unwrap();
    assert_eq!(output.status.code(), Some(0));
    let text = stdout(&output);
    assert_eq!(
        text.lines()
            .filter(|l| l.starts_with("Ack ") && !l.starts_with("Ack wait"))
            .count(),
        217,
        "chunks plus start and finish"
    );
}

#[test]
fn a_model_with_two_collections_shows_which_is_which() {
    let path = image_file("two-collections");
    let output = unkludge(&[
        "--dry-run",
        "--pid",
        "01B8",
        "screen",
        path.to_str().unwrap(),
    ]);
    std::fs::remove_file(&path).unwrap();
    assert_eq!(output.status.code(), Some(0), "{}", stderr(&output));
    let text = stdout(&output);
    assert!(text.contains("main:   09 0D"), "{text}");
    assert!(text.contains("screen: 09 0D"), "{text}");
    assert!(text.contains("screen: 09 0C"), "{text}");
    assert!(!text.contains("main:   09 0C"), "{text}");
}
