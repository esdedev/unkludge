//! Runs the real binary, as built for tests. That build has the protocol crate's `fake` feature on,
//! so it can't open a keyboard. Even so, nothing here may run a command that writes without
//! `--dry-run`, in case that ever stops being true.

use std::path::PathBuf;
use std::process::{Command, Output};
use std::time::Duration;

use unkludge_shared::device_lock::{DeviceLock, Place};

fn unkludge(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_unkludge"))
        .args(args)
        .output()
        .unwrap()
}

fn stdout(output: &Output) -> String {
    String::from_utf8(output.stdout.clone()).unwrap()
}

fn stderr(output: &Output) -> String {
    String::from_utf8(output.stderr.clone()).unwrap()
}

#[test]
fn models_lists_the_29_and_needs_no_keyboard() {
    let output = unkludge(&["models"]);
    assert_eq!(output.status.code(), Some(0));
    let text = stdout(&output);
    assert_eq!(text.lines().count(), 1 + 29);
    assert!(text.contains("0265 RK S85 ES"));
}

#[test]
fn models_as_markdown_says_what_it_is_and_lists_the_29() {
    let output = unkludge(&["models", "--markdown"]);
    assert_eq!(output.status.code(), Some(0));
    let text = stdout(&output);
    assert!(text.starts_with("# Supported models\n"), "{text}");
    assert!(
        text.contains("Generated by `unkludge models --markdown`"),
        "{text}"
    );
    assert_eq!(text.matches("| `258A:").count(), 29, "{text}");
    assert!(text.contains("| `258A:0265` | RK S85 ES | 320x172 | 60 |"));
}

/// Whatever's in the file, even something that isn't text, as when a shell wrote UTF-16.
fn models_file_is_current(file: &[u8], printed: &str) -> bool {
    String::from_utf8_lossy(file).replace("\r\n", "\n") == printed
}

#[test]
fn the_list_in_docs_is_what_the_command_prints() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/MODELS.md");
    assert!(
        models_file_is_current(
            &std::fs::read(path).unwrap(),
            &stdout(&unkludge(&["models", "--markdown"]))
        ),
        "docs/MODELS.md is out of date: CONTRIBUTING.md says how to regenerate it"
    );
}

#[test]
fn a_list_in_docs_in_utf16_is_only_out_of_date() {
    let printed = "# Supported models\n";
    let mut utf16 = vec![0xFF, 0xFE];
    utf16.extend(printed.encode_utf16().flat_map(u16::to_le_bytes));
    assert!(!models_file_is_current(&utf16, printed));
    assert!(models_file_is_current(printed.as_bytes(), printed));
    assert!(models_file_is_current(
        printed.replace('\n', "\r\n").as_bytes(),
        printed
    ));
}

#[test]
fn a_dry_run_without_pid_is_an_error_that_says_so() {
    for command in ["info", "light", "clock", "report"] {
        let output = unkludge(&["--dry-run", command]);
        assert_eq!(output.status.code(), Some(1), "{command}");
        assert!(output.stdout.is_empty(), "{command}");
        let text = stderr(&output);
        assert!(text.starts_with("error: "), "{text}");
        assert!(text.contains("--dry-run needs --pid"), "{text}");
    }
}

